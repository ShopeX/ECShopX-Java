package cn.shopex.ecshopx.orders.service.normal.shopadmin;

import cn.shopex.ecshopx.orders.service.normal.create.NormalOrderCreateState;
import java.util.Map;

public class ShopadminDeferredOrderSnapshot {

	private long orderId;
	private long companyId;
	private String status;
	private String payType;
	private int totalFee;
	private String tradeId;
	private long createdAt;
	private long expireAt;
	private Map<String, Object> params;
	private Map<String, Object> orderData;

	public long getOrderId() {
		return orderId;
	}

	public void setOrderId(long orderId) {
		this.orderId = orderId;
	}

	public long getCompanyId() {
		return companyId;
	}

	public void setCompanyId(long companyId) {
		this.companyId = companyId;
	}

	public String getStatus() {
		return status;
	}

	public void setStatus(String status) {
		this.status = status;
	}

	public String getPayType() {
		return payType;
	}

	public void setPayType(String payType) {
		this.payType = payType;
	}

	public int getTotalFee() {
		return totalFee;
	}

	public void setTotalFee(int totalFee) {
		this.totalFee = totalFee;
	}

	public String getTradeId() {
		return tradeId;
	}

	public void setTradeId(String tradeId) {
		this.tradeId = tradeId;
	}

	public long getCreatedAt() {
		return createdAt;
	}

	public void setCreatedAt(long createdAt) {
		this.createdAt = createdAt;
	}

	public long getExpireAt() {
		return expireAt;
	}

	public void setExpireAt(long expireAt) {
		this.expireAt = expireAt;
	}

	public Map<String, Object> getParams() {
		return params;
	}

	public void setParams(Map<String, Object> params) {
		this.params = params;
	}

	public Map<String, Object> getOrderData() {
		return orderData;
	}

	public void setOrderData(Map<String, Object> orderData) {
		this.orderData = orderData;
	}

	public NormalOrderCreateState toCreateState() {
		NormalOrderCreateState state = new NormalOrderCreateState();
		if (params != null) {
			state.getParams().putAll(params);
		}
		if (orderData != null) {
			state.setOrderData(orderData);
		}
		return state;
	}
}
